def runQemuWithTimedVgaTrace(
    command: list[str],
    projectRoot: Path,
    traceQmpSocketPath: Path,
    traceDumpPath: Path,
    timeoutSeconds: float,
    lineObserver: Callable[[str], None] | None = None,
    completionEvent: threading.Event | None = None,
    finishedEvent: threading.Event | None = None,
    failureMessages: list[str] | None = None,
    captureVisibleVga: bool = False,
    vgaCaptureTimeoutSeconds: float = OS_QEMU_VGA_CAPTURE_TIMEOUT_SECONDS,
) -> tuple[str, str, bool, bool, int, bytes | None, bytes | None]:
    """轮询 VGA 验收区，并按最终里程碑或总截止条件回收目标进程。"""
    normalizedCommand = [str(argument) for argument in command]
    print(f"+ {shlex.join(normalizedCommand)}", flush=True)

    startTime = time.monotonic()
    timedLines: list[str] = []
    capturedOutput = [""]
    capturedDisplaySnapshot: list[bytes | None] = [None]
    capturedTextSnapshot: list[bytes | None] = [None]
    captureFailedEvent = threading.Event()
    displayCapturedEvent = threading.Event()
    localFinishedEvent = finishedEvent or threading.Event()
    capturedFailureMessages = failureMessages if failureMessages is not None else []
    qemuProcess = subprocess.Popen(
        normalizedCommand,
        cwd=projectRoot,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    def captureVgaTrace() -> None:
        connectionDeadline = (
            time.monotonic() + OS_QEMU_QMP_STARTUP_TIMEOUT_SECONDS
        )
        while (
            not traceQmpSocketPath.exists()
            and not localFinishedEvent.is_set()
            and time.monotonic() < connectionDeadline
        ):
            time.sleep(OS_QEMU_QMP_RETRY_INTERVAL_SECONDS)
        if localFinishedEvent.is_set():
            return
        pendingLine = ""
        snapshotSizeBytes = OS_QEMU_VGA_TRACE_CAPTURE_CHUNK_SIZE_BYTES
        displayDumpPath = traceDumpPath.with_name("vga-display.ppm")
        textDumpPath = traceDumpPath.with_name("vga-text.bin")
        try:
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as qmpSocket:
                qmpSocket.settimeout(OS_QEMU_QMP_STARTUP_TIMEOUT_SECONDS)
                qmpSocket.connect(str(traceQmpSocketPath))
                with qmpSocket.makefile("rwb", buffering=0) as qmpStream:
                    greetingLine = qmpStream.readline()
                    if not greetingLine:
                        raise OsToolError("QMP 未返回 VGA 捕获握手信息。")
                    greeting = json.loads(greetingLine.decode("utf-8"))
                    if "QMP" not in greeting:
                        raise OsToolError("QMP VGA 捕获握手缺少版本对象。")
                    sendQmpCommand(qmpStream, {"execute": "qmp_capabilities"})
                    while not localFinishedEvent.is_set():
                        snapshot = readVgaTraceSnapshot(
                            qmpStream,
                            traceDumpPath,
                            snapshotSizeBytes,
                        )
                        requiredSizeBytes = requiredVgaTraceSnapshotSize(snapshot)
                        if requiredSizeBytes > snapshotSizeBytes:
                            snapshotSizeBytes = roundedVgaTraceSnapshotSize(
                                requiredSizeBytes
                            )
                            continue
                        output = decodeVgaTraceSnapshot(snapshot)
                        previousOutput = capturedOutput[0]
                        if not output.startswith(previousOutput):
                            raise OsToolError("VGA 验收区内容发生非追加修改")
                        delta = output[len(previousOutput):]
                        capturedOutput[0] = output
                        pendingLine += delta
                        while "\n" in pendingLine:
                            lineEnd = pendingLine.index("\n") + 1
                            line = pendingLine[:lineEnd]
                            pendingLine = pendingLine[lineEnd:]
                            elapsedMilliseconds = int(
                                (time.monotonic() - startTime) * 1000
                            )
                            timedLines.append(
                                f"[QEMU][T+{elapsedMilliseconds:06d}ms] "
                                f"{line.rstrip(chr(13) + chr(10))}\n"
                            )
                            if lineObserver is not None:
                                lineObserver(line)
                        if (
                            captureVisibleVga
                            and completionEvent is not None
                            and completionEvent.is_set()
                            and not displayCapturedEvent.is_set()
                        ):
                            capturedDisplaySnapshot[0] = readVgaDisplaySnapshot(
                                qmpStream,
                                displayDumpPath,
                            )
                            capturedTextSnapshot[0] = readVgaTextSnapshot(
                                qmpStream,
                                textDumpPath,
                            )
                            displayCapturedEvent.set()
                        time.sleep(OS_QEMU_VGA_TRACE_POLL_INTERVAL_SECONDS)
        except (OSError, ValueError, OsToolError) as error:
            if not localFinishedEvent.is_set() and qemuProcess.poll() is None:
                capturedFailureMessages.append(str(error))
                captureFailedEvent.set()
                if completionEvent is not None:
                    completionEvent.set()

    captureThread = threading.Thread(
        target=captureVgaTrace,
        name="os-qemu-vga-trace-capture",
        daemon=True,
    )
    captureThread.start()

    timedOut = False
    completedByObserver = False
    try:
        completionDeadline = startTime + timeoutSeconds
        while qemuProcess.poll() is None:
            if captureFailedEvent.is_set():
                break
            if completionEvent is not None and completionEvent.is_set():
                completedByObserver = True
                if captureVisibleVga and not displayCapturedEvent.wait(
                    vgaCaptureTimeoutSeconds
                ):
                    if not captureFailedEvent.is_set():
                        capturedFailureMessages.append("QMP 未在期限内捕获 VGA 可见画面")
                        captureFailedEvent.set()
                time.sleep(OS_QEMU_COMPLETION_SETTLE_SECONDS)
                break
            remainingSeconds = completionDeadline - time.monotonic()
            if remainingSeconds <= 0.0:
                timedOut = True
                break
            waitSeconds = min(
                remainingSeconds,
                OS_QEMU_COMPLETION_POLL_INTERVAL_SECONDS,
            )
            if completionEvent is None:
                time.sleep(waitSeconds)
            else:
                completionEvent.wait(waitSeconds)

        if qemuProcess.poll() is None:
            localFinishedEvent.set()
            qemuProcess.terminate()
            try:
                returnCode = qemuProcess.wait(
                    timeout=OS_QEMU_TERMINATION_TIMEOUT_SECONDS
                )
            except subprocess.TimeoutExpired:
                qemuProcess.kill()
                returnCode = qemuProcess.wait()
        else:
            returnCode = qemuProcess.returncode
    finally:
        if qemuProcess.poll() is None:
            qemuProcess.kill()
            qemuProcess.wait()
        localFinishedEvent.set()
        captureThread.join()

    return (
        capturedOutput[0],
        "".join(timedLines),
        timedOut,
        completedByObserver,
        returnCode,
        capturedDisplaySnapshot[0],
        capturedTextSnapshot[0],
    )


def waitForQmpResponse(
    qmpStream: socket.SocketIO,
) -> dict[str, object]:
    for _ in range(OS_QEMU_QMP_MAXIMUM_RESPONSE_COUNT):
        responseLine = qmpStream.readline()
        if not responseLine:
            raise OsToolError("QMP 在返回命令结果前关闭连接。")
        response = json.loads(responseLine.decode("utf-8"))
        if "return" in response or "error" in response:
            return response
    raise OsToolError("QMP 返回事件过多，未找到命令结果。")


def sendQmpCommand(
    qmpStream: socket.SocketIO,
    command: dict[str, object],
) -> dict[str, object]:
    qmpStream.write(
        json.dumps(command, separators=(",", ":")).encode("utf-8")
        + b"\r\n"
    )
    qmpStream.flush()
    response = waitForQmpResponse(qmpStream)
    if "error" in response:
        raise OsToolError(f"QMP 命令执行失败：{response['error']!r}")
    return response


def qemuKeyNameForCharacter(character: str) -> str:
    if len(character) != 1:
        raise OsToolError("QEMU 键盘映射只接受单个字符。")
    if "a" <= character <= "z" or "0" <= character <= "9":
        return character
    if "A" <= character <= "Z":
        return f"shift-{character.lower()}"
    keyNames = {
        "\x03": "ctrl-c",
        "\x1a": "ctrl-z",
        "\x02": "left",
        "\x06": "right",
        "\x10": "up",
        "\x0e": "down",
        "\t": "tab",
        "\n": "ret",
        " ": "spc",
        "/": "slash",
        ".": "dot",
        "-": "minus",
        "=": "equal",
        ";": "semicolon",
        ",": "comma",
        "&": "shift-7",
        "<": "shift-comma",
        ">": "shift-dot",
        "|": "shift-backslash",
        "\\": "backslash",
        "_": "shift-minus",
        "$": "shift-4",
        "*": "shift-8",
        "?": "shift-slash",
        "{": "shift-leftbracket",
        "}": "shift-rightbracket",
        "'": "apostrophe",
        '"': "shift-apostrophe",
    }
    if character not in keyNames:
        raise OsToolError(
            f"QEMU 键盘输入包含未支持字符：{character!r}"
        )
    return keyNames[character]


def waitForQemuKeyboardProgress(
    progressCondition: threading.Condition,
    markerCounts: dict[str, int],
    marker: str,
    expectedCount: int,
    finishedEvent: threading.Event,
    stepTimeoutSeconds: float,
) -> bool:
    progressDeadline = time.monotonic() + stepTimeoutSeconds
    with progressCondition:
        while markerCounts.get(marker, 0) < expectedCount:
            if finishedEvent.is_set():
                return False
            remainingSeconds = progressDeadline - time.monotonic()
            if remainingSeconds <= 0.0:
                raise OsToolError(
                    "QEMU 键盘分步注入等待VGA标记超时："
                    f"{marker!r} 第 {expectedCount} 次"
                )
            progressCondition.wait(
                min(remainingSeconds, OS_QEMU_COMPLETION_POLL_INTERVAL_SECONDS)
            )
    return True


def injectQemuText(
    qmpSocketPath: Path,
    inputText: str,
    readyTimeoutSeconds: float,
    readyEvent: threading.Event,
    finishedEvent: threading.Event,
    failureMessages: list[str],
    progressCondition: threading.Condition,
    markerCounts: dict[str, int],
    failureEvent: threading.Event,
    stepTimeoutSeconds: float,
) -> None:
    if not readyEvent.wait(readyTimeoutSeconds):
        return

    connectionDeadline = (
        time.monotonic() + OS_QEMU_QMP_STARTUP_TIMEOUT_SECONDS
    )
    while (
        not qmpSocketPath.exists()
        and not finishedEvent.is_set()
        and time.monotonic() < connectionDeadline
    ):
        time.sleep(OS_QEMU_QMP_RETRY_INTERVAL_SECONDS)
    if finishedEvent.is_set():
        return

    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as qmpSocket:
            qmpSocket.settimeout(OS_QEMU_QMP_STARTUP_TIMEOUT_SECONDS)
            qmpSocket.connect(str(qmpSocketPath))
            with qmpSocket.makefile("rwb", buffering=0) as qmpStream:
                greetingLine = qmpStream.readline()
                if not greetingLine:
                    raise OsToolError("QMP 未返回握手信息。")
                greeting = json.loads(greetingLine.decode("utf-8"))
                if "QMP" not in greeting:
                    raise OsToolError("QMP 握手缺少版本对象。")
                sendQmpCommand(qmpStream, {"execute": "qmp_capabilities"})
                expectedCommandCompletionCount = 0
                for characterIndex, character in enumerate(inputText):
                    if finishedEvent.is_set():
                        return
                    nextCharacter = (
                        inputText[characterIndex + 1]
                        if characterIndex + 1 < len(inputText)
                        else ""
                    )
                    foregroundWaitTarget = 0
                    continueDeliveryTarget = 0
                    if (
                        character == "\n" and
                        nextCharacter in ("\x03", "\x1a")
                    ):
                        with progressCondition:
                            foregroundWaitTarget = (
                                markerCounts.get(
                                    OS_QEMU_USER_SHELL_FOREGROUND_JOB_WAITING_MARKER,
                                    0,
                                ) + 1
                            )
                            if nextCharacter == "\x03":
                                continueDeliveryTarget = (
                                    markerCounts.get(
                                        OS_QEMU_KERNEL_SIGNAL_DEFAULT_CONTINUE_DELIVERED_MARKER,
                                        0,
                                    ) + 1
                                )
                    keyName = qemuKeyNameForCharacter(character)
                    sendQmpCommand(
                        qmpStream,
                        {
                            "execute": "human-monitor-command",
                            "arguments": {
                                "command-line": f"sendkey {keyName} 1",
                            },
                        },
                    )
                    time.sleep(OS_QEMU_KEY_INJECTION_INTERVAL_SECONDS)
                    if (
                        character == "\n" and
                        nextCharacter in ("\x03", "\x1a")
                    ):
                        if not waitForQemuKeyboardProgress(
                            progressCondition,
                            markerCounts,
                            OS_QEMU_USER_SHELL_FOREGROUND_JOB_WAITING_MARKER,
                            foregroundWaitTarget,
                            finishedEvent,
                            stepTimeoutSeconds,
                        ):
                            return
                        if nextCharacter == "\x03" and not waitForQemuKeyboardProgress(
                            progressCondition,
                            markerCounts,
                            OS_QEMU_KERNEL_SIGNAL_DEFAULT_CONTINUE_DELIVERED_MARKER,
                            continueDeliveryTarget,
                            finishedEvent,
                            stepTimeoutSeconds,
                        ):
                            return
                    elif character == "\n" or character in ("\x03", "\x1a"):
                        expectedCommandCompletionCount += 1
                        if not waitForQemuKeyboardProgress(
                            progressCondition,
                            markerCounts,
                            OS_QEMU_USER_SHELL_COMMAND_COMPLETE_MARKER,
                            expectedCommandCompletionCount,
                            finishedEvent,
                            stepTimeoutSeconds,
                        ):
                            return
    except (OSError, ValueError, OsToolError) as error:
        failureMessages.append(str(error))
        # 注入线程一旦失败就立即结束有界整机运行，避免继续空等总超时预算。
        failureEvent.set()


def validateVgaProtocol(
    vgaOutput: str,
    requiredMarkers: tuple[str, ...],
    forbiddenMarkers: tuple[str, ...],
    expectedMarkerCounts: tuple[tuple[str, int], ...] = (),
    minimumHexMarkerValues: tuple[tuple[str, int], ...] = (),
) -> None:
    for forbiddenMarker in forbiddenMarkers:
        if forbiddenMarker in vgaOutput:
            raise OsToolError(
                f"VGA输出包含禁止标记：{forbiddenMarker!r}"
            )

    previousMarkerPosition = 0
    for requiredMarker in requiredMarkers:
        markerPosition = vgaOutput.find(
            requiredMarker,
            previousMarkerPosition,
        )
        if markerPosition < 0:
            raise OsToolError(
                "VGA输出缺少必需标记或标记顺序错误："
                f"{requiredMarker!r}"
            )
        previousMarkerPosition = markerPosition + len(requiredMarker)

    for marker, expectedCount in expectedMarkerCounts:
        actualCount = vgaOutput.count(marker)
        if actualCount != expectedCount:
            raise OsToolError(
                "VGA标记出现次数不正确："
                f"{marker!r} 实际 {actualCount} 次，预期 {expectedCount} 次"
            )

    for marker, minimumValue in minimumHexMarkerValues:
        markerPattern = re.compile(
            re.escape(marker) + r"([0-9A-Fa-f]{16})(?:\r?\n|$)"
        )
        markerValues = [
            int(match.group(1), 16)
            for match in markerPattern.finditer(vgaOutput)
        ]
        if not markerValues or min(markerValues) < minimumValue:
            raise OsToolError(
                "VGA十六进制统计未达到下界："
                f"{marker!r} 下界 {minimumValue}"
            )


def runQemuFirmwareBoot(
    projectRoot: Path,
    firmwareImagePath: Path,
    diskImagePath: Path,
    expectedFirmwareSizeBytes: int,
    expectedDiskSizeBytes: int,
    requiredMarkers: tuple[str, ...],
    forbiddenMarkers: tuple[str, ...],
    keyboardInputText: str | None = None,
    keyboardReadyMarker: str = OS_QEMU_KERNEL_READY_MARKER,
    expectedMarkerCounts: tuple[tuple[str, int], ...] = (),
    minimumHexMarkerValues: tuple[tuple[str, int], ...] = (),
    persistentDiskWrites: bool = False,
    memoryMebibytes: int = OS_QEMU_MINIMUM_GUEST_MEMORY_MEBIBYTES,
    cpuModel: str = OS_QEMU_DEFAULT_CPU_MODEL,
    keyboardStepTimeoutSeconds: float | None = None,
    vgaCaptureTimeoutSeconds: float = OS_QEMU_VGA_CAPTURE_TIMEOUT_SECONDS,
    swapDiskImagePath: Path | None = None,
    nvmeDiskImagePath: Path | None = None,
    nvmeFailureEvent: str | None = None,
    nvmeSwapDiskImagePath: Path | None = None,
) -> None:
    validateImageSize(
        firmwareImagePath,
        expectedFirmwareSizeBytes,
        "固件 ROM",
    )
    if swapDiskImagePath is not None:
        validateImageSize(swapDiskImagePath, OS_SWAP_IMAGE_SIZE_BYTES, "交换盘镜像")
    if nvmeDiskImagePath is not None:
        validateImageSize(
            nvmeDiskImagePath,
            expectedDiskSizeBytes,
            "NVMe 命名空间镜像",
        )
    if nvmeSwapDiskImagePath is not None:
        validateImageSize(
            nvmeSwapDiskImagePath,
            OS_SWAP_IMAGE_SIZE_BYTES,
            "NVMe swap namespace 镜像",
        )
        if nvmeDiskImagePath is None:
            raise OsToolError("NVMe swap namespace 必须与 root namespace 一起提供。")
    if nvmeFailureEvent is not None and (
        nvmeDiskImagePath is None or
        nvmeFailureEvent not in OS_QEMU_NVME_BLKDEBUG_FAILURE_EVENTS
    ):
        raise OsToolError("NVMe blkdebug 失败事件无效或缺少命名空间镜像。")
    validateImageSize(
        diskImagePath,
        expectedDiskSizeBytes,
        "启动磁盘镜像",
    )

    with tempfile.TemporaryDirectory(prefix="os-qemu-") as temporaryDirectory:
        temporaryPath = Path(temporaryDirectory)
        traceQmpSocketPath = temporaryPath / "vga-trace-qmp.sock"
        inputQmpSocketPath = temporaryPath / "keyboard-qmp.sock"
        traceDumpPath = temporaryPath / "vga-trace.bin"
        nvmeBlkdebugConfigPath: Path | None = None
        activeNvmeDiskImagePath = nvmeDiskImagePath
        if nvmeFailureEvent is not None:
            nvmeBlkdebugConfigPath = temporaryPath / "nvme-blkdebug.conf"
            activeNvmeDiskImagePath = temporaryPath / "nvme-failure.img"
            copySparseImage(nvmeDiskImagePath, activeNvmeDiskImagePath)
            nvmeBlkdebugConfigPath.write_text(
                "[inject-error]\n"
                f'event = "{nvmeFailureEvent}"\n'
                'errno = "5"\n'
                'once = "on"\n',
                encoding="utf-8",
            )
        keyboardReadyEvent = threading.Event()
        protocolCompleteEvent = threading.Event()
        qemuFinishedEvent = threading.Event()
        qmpFailureMessages: list[str] = []
        keyboardProgressCondition = threading.Condition()
        keyboardMarkerCounts = {
            OS_QEMU_USER_SHELL_COMMAND_COMPLETE_MARKER: 0,
            OS_QEMU_USER_SHELL_FOREGROUND_JOB_WAITING_MARKER: 0,
            OS_QEMU_KERNEL_SIGNAL_DEFAULT_CONTINUE_DELIVERED_MARKER: 0,
        }
        finalRequiredMarker = requiredMarkers[-1]
        # 每条系统路径都必须同时证明内存日志与可见 VGA；失败路径不能只靠
        # QMP 日志“通过”，却把用户留在黑屏上。
        captureVisibleVga = len(requiredMarkers) > 0
        firmwareTimeoutSeconds = qemuFirmwareTimeoutSeconds(memoryMebibytes)
        effectiveKeyboardStepTimeoutSeconds = (
            keyboardStepTimeoutSeconds
            if keyboardStepTimeoutSeconds is not None
            else (
                40.0
                if memoryMebibytes >= OS_QEMU_PRIMARY_GUEST_MEMORY_MEBIBYTES
                else OS_QEMU_KEYBOARD_STEP_TIMEOUT_SECONDS
            )
        )

        def observeVgaLine(line: str) -> None:
            if keyboardReadyMarker in line:
                keyboardReadyEvent.set()
            with keyboardProgressCondition:
                for marker in keyboardMarkerCounts:
                    keyboardMarkerCounts[marker] += line.count(marker)
                keyboardProgressCondition.notify_all()
            if any(forbiddenMarker in line for forbiddenMarker in forbiddenMarkers):
                protocolCompleteEvent.set()
            if finalRequiredMarker in line:
                protocolCompleteEvent.set()

        qmpThread: threading.Thread | None = None
        if keyboardInputText is not None:
            qmpThread = threading.Thread(
                target=injectQemuText,
                args=(
                    inputQmpSocketPath,
                    keyboardInputText,
                    firmwareTimeoutSeconds,
                    keyboardReadyEvent,
                    qemuFinishedEvent,
                    qmpFailureMessages,
                    keyboardProgressCondition,
                    keyboardMarkerCounts,
                    protocolCompleteEvent,
                    effectiveKeyboardStepTimeoutSeconds,
                ),
                name="os-qemu-keyboard-injection",
                daemon=True,
            )
            qmpThread.start()

        command = createQemuFirmwareCommand(
            firmwareImagePath,
            diskImagePath,
            (
                (traceQmpSocketPath, inputQmpSocketPath)
                if keyboardInputText is not None
                else (traceQmpSocketPath,)
            ),
            persistentDiskWrites,
            memoryMebibytes,
            cpuModel,
            "none",
            swapDiskImagePath,
            activeNvmeDiskImagePath,
            nvmeBlkdebugConfigPath,
            nvmeSwapDiskImagePath,
        )
        try:
            (
                vgaOutput,
                timedVgaOutput,
                timedOut,
                completedByObserver,
                returnCode,
                vgaDisplaySnapshot,
                vgaTextSnapshot,
            ) = runQemuWithTimedVgaTrace(
                command,
                projectRoot,
                traceQmpSocketPath,
                traceDumpPath,
                firmwareTimeoutSeconds,
                observeVgaLine,
                protocolCompleteEvent,
                qemuFinishedEvent,
                qmpFailureMessages,
                captureVisibleVga,
                vgaCaptureTimeoutSeconds,
            )
        finally:
            qemuFinishedEvent.set()
            keyboardReadyEvent.set()
            if qmpThread is not None:
                qmpThread.join()

    if qmpFailureMessages:
        print(timedVgaOutput, end="")
        raise OsToolError(
            "QEMU VGA 捕获或键盘注入失败：" + "; ".join(qmpFailureMessages)
        )
    if captureVisibleVga:
        if vgaDisplaySnapshot is None:
            print(timedVgaOutput if timedVgaOutput else vgaOutput, end="")
            raise OsToolError("QEMU 没有返回 VGA 可见画面")
        validateVgaDisplaySnapshot(vgaDisplaySnapshot)
        if vgaTextSnapshot is None:
            print(timedVgaOutput if timedVgaOutput else vgaOutput, end="")
            raise OsToolError("QEMU 没有返回 VGA 文本快照")
        if OS_QEMU_KERNEL_READY_MARKER in requiredMarkers:
            validateVgaTerminalSnapshot(vgaTextSnapshot)
    if timedOut or completedByObserver:
        try:
            validateVgaProtocol(
                vgaOutput,
                requiredMarkers,
                forbiddenMarkers,
                expectedMarkerCounts,
                minimumHexMarkerValues,
            )
        except OsToolError as protocolError:
            print(timedVgaOutput, end="")
            if timedOut:
                raise OsToolError(
                    "QEMU 固件测试超过有界墙钟预算 "
                    f"{firmwareTimeoutSeconds:.1f} 秒：{protocolError}"
                ) from protocolError
            raise
        print(timedVgaOutput, end="")
        print("QEMU 固件 VGA 协议验收通过。")
        return

    raise OsToolError(
        f"QEMU 固件测试异常提前退出：{returnCode}"
    )


def runQemuFileSystemPersistence(
    projectRoot: Path,
    firmwareImagePath: Path,
    diskImagePath: Path,
    expectedFirmwareSizeBytes: int,
    expectedDiskSizeBytes: int,
    swapDiskImagePath: Path,
    nvmeStorage: bool = False,
) -> None:
    """在同一可写磁盘上连续启动两次，并对第三次启动注入超级块损坏。"""
    validateImageSize(
        firmwareImagePath,
        expectedFirmwareSizeBytes,
        "固件 ROM",
    )
    validateImageSize(swapDiskImagePath, OS_SWAP_IMAGE_SIZE_BYTES, "交换盘镜像")
    validateImageSize(
        diskImagePath,
        expectedDiskSizeBytes,
        "启动磁盘镜像",
    )
    forbiddenRuntimeFailureMarkers = (
        OS_QEMU_KERNEL_FILE_SYSTEM_CORRUPT_MARKER,
        OS_QEMU_KERNEL_FATAL_MARKER,
        OS_QEMU_KERNEL_USER_RESULT_INVALID_MARKER,
        OS_QEMU_KERNEL_EXCEPTION_MARKER,
        OS_QEMU_KERNEL_PANIC_MARKER,
        OS_QEMU_USER_VM_FAILURE_MARKER,
    )
    with tempfile.TemporaryDirectory(
        prefix="os-qemu-file-system-"
    ) as temporaryDirectory:
        writableDiskPath = Path(temporaryDirectory) / "persistent_disk.img"
        writableSwapDiskPath = Path(temporaryDirectory) / "persistent_swap.img"
        copySparseImage(diskImagePath, writableDiskPath)
        copySparseImage(swapDiskImagePath, writableSwapDiskPath)
        writableNvmeRootPath: Path | None = None
        writableNvmeSwapPath: Path | None = None
        if nvmeStorage:
            writableNvmeRootPath = Path(temporaryDirectory) / "persistent_nvme_root.img"
            writableNvmeSwapPath = Path(temporaryDirectory) / "persistent_nvme_swap.img"
            copySparseImage(diskImagePath, writableNvmeRootPath)
            copySparseImage(swapDiskImagePath, writableNvmeSwapPath)
        storageReadyMarkers = (
            (
                OS_QEMU_KERNEL_STORAGE_BACKEND_NVME_MARKER,
                OS_QEMU_KERNEL_NVME_STORAGE_READY_MARKER,
            )
            if nvmeStorage
            else (OS_QEMU_KERNEL_STORAGE_BACKEND_ATA_MARKER,)
        )

        runQemuFirmwareBoot(
            projectRoot,
            firmwareImagePath,
            writableDiskPath,
            expectedFirmwareSizeBytes,
            expectedDiskSizeBytes,
            (
                *storageReadyMarkers,
                OS_QEMU_KERNEL_ROOTFS_V4_MOUNTED_MARKER,
                OS_QEMU_KERNEL_ROOTFS_JOURNAL_READY_MARKER,
                OS_QEMU_USER_FILE_WRITTEN_MARKER,
                OS_QEMU_USER_FILE_VERIFIED_MARKER,
                OS_QEMU_KERNEL_FILE_SYSTEM_SYNCED_MARKER,
                OS_QEMU_KERNEL_FILE_SYSTEM_PAYLOAD_VALID_MARKER,
                OS_QEMU_KERNEL_READY_MARKER,
            ),
            forbiddenRuntimeFailureMarkers +
            (OS_QEMU_KERNEL_FILE_SYSTEM_PERSISTENCE_RESTORED_MARKER,),
            keyboardInputText=OS_QEMU_USER_SHELL_FUNCTIONAL_TEST_INPUT,
            keyboardReadyMarker=(
                OS_QEMU_KERNEL_IO_FIRST_DESCRIPTOR_READ_BLOCK_MARKER
            ),
            persistentDiskWrites=True,
            memoryMebibytes=OS_QEMU_FUNCTIONAL_GUEST_MEMORY_MEBIBYTES,
            keyboardStepTimeoutSeconds=40.0,
            vgaCaptureTimeoutSeconds=10.0,
            swapDiskImagePath=writableSwapDiskPath,
            nvmeDiskImagePath=writableNvmeRootPath,
            nvmeSwapDiskImagePath=writableNvmeSwapPath,
        )
        runQemuFirmwareBoot(
            projectRoot,
            firmwareImagePath,
            writableDiskPath,
            expectedFirmwareSizeBytes,
            expectedDiskSizeBytes,
            (
                *storageReadyMarkers,
                OS_QEMU_KERNEL_ROOTFS_V4_MOUNTED_MARKER,
                OS_QEMU_KERNEL_ROOTFS_JOURNAL_READY_MARKER,
                OS_QEMU_KERNEL_FILE_SYSTEM_PERSISTENCE_RESTORED_MARKER,
                OS_QEMU_USER_FILE_WRITTEN_MARKER,
                OS_QEMU_USER_FILE_VERIFIED_MARKER,
                OS_QEMU_KERNEL_FILE_SYSTEM_PAYLOAD_VALID_MARKER,
                OS_QEMU_KERNEL_READY_MARKER,
            ),
            forbiddenRuntimeFailureMarkers,
            keyboardInputText=OS_QEMU_USER_SHELL_FUNCTIONAL_TEST_INPUT,
            keyboardReadyMarker=(
                OS_QEMU_KERNEL_IO_FIRST_DESCRIPTOR_READ_BLOCK_MARKER
            ),
            persistentDiskWrites=True,
            memoryMebibytes=OS_QEMU_FUNCTIONAL_GUEST_MEMORY_MEBIBYTES,
            keyboardStepTimeoutSeconds=40.0,
            vgaCaptureTimeoutSeconds=10.0,
            swapDiskImagePath=writableSwapDiskPath,
            nvmeDiskImagePath=writableNvmeRootPath,
            nvmeSwapDiskImagePath=writableNvmeSwapPath,
        )

        persistentRootPath = (
            writableNvmeRootPath if writableNvmeRootPath is not None else writableDiskPath
        )
        superblockByteOffset = (
            OS_QEMU_FILE_SYSTEM_START_LBA *
            OS_QEMU_FILE_SYSTEM_SECTOR_SIZE_BYTES +
            OS_QEMU_FILE_SYSTEM_CORRUPTION_OFFSET_BYTES
        )
        with persistentRootPath.open("r+b") as writableDisk:
            writableDisk.seek(superblockByteOffset)
            originalByte = writableDisk.read(1)
            if len(originalByte) != 1:
                raise OsToolError("无法读取文件系统超级块故障注入字节。")
            writableDisk.seek(superblockByteOffset)
            writableDisk.write(
                bytes(
                    (
                        originalByte[0] ^
                        OS_QEMU_FILE_SYSTEM_CORRUPTION_MASK,
                    )
                )
            )

        runQemuFirmwareBoot(
            projectRoot,
            firmwareImagePath,
            writableDiskPath,
            expectedFirmwareSizeBytes,
            expectedDiskSizeBytes,
            (OS_QEMU_KERNEL_FILE_SYSTEM_CORRUPT_MARKER,),
            (
                OS_QEMU_KERNEL_USER_RING3_ENTER_MARKER,
                OS_QEMU_KERNEL_FILE_SYSTEM_PAYLOAD_VALID_MARKER,
                OS_QEMU_KERNEL_READY_MARKER,
            ),
            persistentDiskWrites=True,
            memoryMebibytes=OS_QEMU_FUNCTIONAL_GUEST_MEMORY_MEBIBYTES,
            swapDiskImagePath=writableSwapDiskPath,
            nvmeDiskImagePath=writableNvmeRootPath,
            nvmeSwapDiskImagePath=writableNvmeSwapPath,
            vgaCaptureTimeoutSeconds=10.0,
        )
