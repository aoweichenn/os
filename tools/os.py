def handleCopyFilePrefix(arguments: argparse.Namespace) -> None:
    if not arguments.sourcePath.is_file():
        raise OsToolError(f"源文件不存在：{arguments.sourcePath}")
    if arguments.lengthBytes <= 0:
        raise OsToolError("文件前缀长度必须大于零。")
    sourceBytes = arguments.sourcePath.read_bytes()
    if arguments.lengthBytes > len(sourceBytes):
        raise OsToolError(
            "文件前缀长度不能超过源文件长度："
            f"{arguments.lengthBytes} > {len(sourceBytes)}"
        )
    arguments.destinationPath.parent.mkdir(parents=True, exist_ok=True)
    arguments.destinationPath.write_bytes(
        sourceBytes[: arguments.lengthBytes]
    )


