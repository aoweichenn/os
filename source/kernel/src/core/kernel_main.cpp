struct KernelStorageDevices final {
    BlockDevice *root_device;
    BlockDevice *swap_device;
    AsynchronousBlockDevice *root_asynchronous_device;
    AsynchronousBlockDevice *swap_asynchronous_device;
    NvmeStorageRuntimeResult nvme_result;
    bool nvme_active;
};

[[nodiscard]] KernelStorageDevices
SelectKernelStorageDevices(const VgaTextConsole &vga_console) noexcept {
    KernelStorageDevices devices{
        .root_device = &GetRuntimeAtaRootBlockDevice(),
        .swap_device = &GetRuntimeAtaSwapBlockDevice(),
        .root_asynchronous_device = &GetRuntimeAtaRootAsynchronousBlockDevice(),
        .swap_asynchronous_device = &GetRuntimeAtaSwapAsynchronousBlockDevice(),
        .nvme_result = NvmeStorageRuntimeResult{},
        .nvme_active = false,
    };
    BlockDevice *nvme_root_device = nullptr;
    BlockDevice *nvme_swap_device = nullptr;
    AsynchronousBlockDevice *nvme_root_asynchronous_device = nullptr;
    AsynchronousBlockDevice *nvme_swap_asynchronous_device = nullptr;
    const NvmeStatus status = InitializeNvmeStorageRuntime(
        GetMonotonicNanoseconds, devices.nvme_result, nvme_root_device, nvme_swap_device,
        nvme_root_asynchronous_device, nvme_swap_asynchronous_device);
    if (status == NvmeStatus::Succeeded && nvme_root_device != nullptr &&
        nvme_swap_device != nullptr && nvme_root_asynchronous_device != nullptr &&
        nvme_swap_asynchronous_device != nullptr) {
        devices.root_device = nvme_root_device;
        devices.swap_device = nvme_swap_device;
        devices.root_asynchronous_device = nvme_root_asynchronous_device;
        devices.swap_asynchronous_device = nvme_swap_asynchronous_device;
        devices.nvme_active = true;
        WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_STORAGE_BACKEND_NVME_MESSAGE);
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_NVME_ROOT_NAMESPACE_BLOCK_COUNT_PREFIX,
                             devices.nvme_result.root_geometry.logical_block_count);
        WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_NVME_ROOT_NAMESPACE_READY_MESSAGE);
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_NVME_SWAP_NAMESPACE_BLOCK_COUNT_PREFIX,
                             devices.nvme_result.swap_geometry.logical_block_count);
        WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_NVME_SWAP_NAMESPACE_READY_MESSAGE);
        WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_NVME_STORAGE_READY_MESSAGE);
        return devices;
    }
    if (status == NvmeStatus::SecondaryNamespaceUnavailable) {
        // 单 namespace 设备仍用于驱动验收；完成自检后，系统存储明确回退 ATA。
        ProbeKernelNvme(vga_console);
    } else if (status != NvmeStatus::NotFound) {
        if (status == NvmeStatus::ResourceLeak) {
            HaltProcessor();
        }
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_NVME_STORAGE_FALLBACK_PREFIX,
                             static_cast<uint64_t>(status));
    }
    WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_STORAGE_BACKEND_ATA_MESSAGE);
    return devices;
}

[[nodiscard]] uint8_t ExpectedFileSystemPayloadByte(const uint64_t byte_index) noexcept {
    return static_cast<uint8_t>((byte_index * OS_KERNEL_MAIN_FILE_SYSTEM_BYTE_MULTIPLIER +
                                 OS_KERNEL_MAIN_FILE_SYSTEM_BYTE_INCREMENT) &
                                OS_KERNEL_MAIN_FILE_SYSTEM_BYTE_MASK);
}

[[nodiscard]] fs::Status ValidateFileSystemPayload(fs::Vfs &vfs,
                                                   const fs::FsContext &context) noexcept {
    const fs::OpenOptions options{
        .readable = true,
        .writable = false,
        .create = false,
        .truncate = false,
        .append = false,
    };
    fs::OpenFile file{};
    const fs::Status open_status =
        vfs.Open(context, OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_PATH,
                 sizeof(OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_PATH), options, file);
    if (open_status != fs::Status::Succeeded) {
        return open_status;
    }
    uint8_t payload[OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_SIZE_BYTES]{};
    uint64_t read_bytes = OS_KERNEL_MAIN_FILE_SYSTEM_EMPTY_VALUE;
    bool valid = vfs.Read(file, payload, sizeof(payload), read_bytes) == fs::Status::Succeeded &&
                 read_bytes == sizeof(payload);
    for (uint64_t byte_index = OS_KERNEL_MAIN_FILE_SYSTEM_EMPTY_VALUE;
         byte_index < OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_SIZE_BYTES; ++byte_index) {
        valid = valid && payload[byte_index] == ExpectedFileSystemPayloadByte(byte_index);
    }
    uint8_t end_of_file_probe = OS_KERNEL_MAIN_FILE_SYSTEM_ZERO_BYTE;
    read_bytes = OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_SIZE_BYTES;
    valid = valid &&
            vfs.Read(file, &end_of_file_probe, sizeof(end_of_file_probe), read_bytes) ==
                fs::Status::Succeeded &&
            read_bytes == OS_KERNEL_MAIN_FILE_SYSTEM_EMPTY_VALUE &&
            vfs.Close(file) == fs::Status::Succeeded;
    return valid ? fs::Status::Succeeded : fs::Status::Corrupt;
}

