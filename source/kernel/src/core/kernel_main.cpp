void CreateRequiredProcess(const VgaTextConsole &vga_console,
                           const UserProgramSelection selection) noexcept {
    ProcessCreationResult creation_result{};
    UserElfValidationStatus elf_validation_status = UserElfValidationStatus::Succeeded;
    UserAddressSpaceStatus address_space_status = UserAddressSpaceStatus::Succeeded;
    const ProcessRuntimeStatus runtime_status =
        CreateProcess(selection, creation_result, elf_validation_status, address_space_status);
    if (runtime_status == ProcessRuntimeStatus::InvalidElf) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_ELF_REJECTED_PREFIX,
                             static_cast<uint64_t>(elf_validation_status));
        HaltProcessor();
    }
    if (runtime_status != ProcessRuntimeStatus::Succeeded) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_ADDRESS_SPACE_FAILED_PREFIX,
                             static_cast<uint64_t>(address_space_status));
        HaltProcessor();
    }
    WriteProcessCreationSuccess(vga_console, creation_result);
}

void CreateInitialDiskProcess(const VgaTextConsole &vga_console,
                              const UserProgramSelection selection) noexcept {
    const KernelProgramString arguments[]{
        KernelProgramString{
            .data = reinterpret_cast<const uint8_t *>(OS_KERNEL_MAIN_INIT_PATH),
            .length_bytes =
                sizeof(OS_KERNEL_MAIN_INIT_PATH) - OS_KERNEL_MAIN_STRING_TERMINATOR_SIZE_BYTES,
        },
    };
    const KernelProgramString environment[]{
        KernelProgramString{
            .data = reinterpret_cast<const uint8_t *>(OS_KERNEL_MAIN_INIT_ENVIRONMENT),
            .length_bytes = sizeof(OS_KERNEL_MAIN_INIT_ENVIRONMENT) -
                            OS_KERNEL_MAIN_STRING_TERMINATOR_SIZE_BYTES,
        },
        KernelProgramString{
            .data = reinterpret_cast<const uint8_t *>(OS_KERNEL_MAIN_OOM_PRESSURE_ENVIRONMENT),
            .length_bytes = sizeof(OS_KERNEL_MAIN_OOM_PRESSURE_ENVIRONMENT) -
                            OS_KERNEL_MAIN_STRING_TERMINATOR_SIZE_BYTES,
        },
    };
    const uint64_t environment_count = selection == UserProgramSelection::OomPressure ? 2ULL : 1ULL;
    ProcessCreationResult creation_result{};
    UserElfValidationStatus elf_validation_status = UserElfValidationStatus::Succeeded;
    UserAddressSpaceStatus address_space_status = UserAddressSpaceStatus::Succeeded;
    const ProcessRuntimeStatus runtime_status = CreateInitialProcessFromPath(
        reinterpret_cast<const uint8_t *>(OS_KERNEL_MAIN_INIT_PATH),
        sizeof(OS_KERNEL_MAIN_INIT_PATH) - OS_KERNEL_MAIN_STRING_TERMINATOR_SIZE_BYTES, arguments,
        sizeof(arguments) / sizeof(arguments[OS_KERNEL_MAIN_FIRST_PROCESS_INDEX]), environment,
        environment_count, creation_result, elf_validation_status, address_space_status);
    if (runtime_status == ProcessRuntimeStatus::InvalidElf) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_ELF_REJECTED_PREFIX,
                             static_cast<uint64_t>(elf_validation_status));
        HaltProcessor();
    }
    if (runtime_status != ProcessRuntimeStatus::Succeeded) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_ADDRESS_SPACE_FAILED_PREFIX,
                             static_cast<uint64_t>(runtime_status));
        HaltProcessor();
    }
    WriteProcessCreationSuccess(vga_console, creation_result);
}

void PrepareRequiredProcesses(const VgaTextConsole &vga_console,
                              const UserProgramSelection selection) noexcept {
    if (InitializeProcessRuntime() != ProcessRuntimeStatus::Succeeded) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_EXECUTION_FAILED_PREFIX,
                             static_cast<uint64_t>(ProcessRuntimeStatus::SchedulerFailure));
        HaltProcessor();
    }
    WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_PROCESS_RUNTIME_READY_MESSAGE);
    const ProcessRuntimeStatistics runtime_statistics = GetProcessRuntimeStatistics();
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_CAPACITY_PREFIX,
                         runtime_statistics.configured_process_capacity);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_THREAD_CAPACITY_PREFIX,
                         runtime_statistics.configured_thread_capacity);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_THREADS_PER_PROCESS_PREFIX,
                         runtime_statistics.configured_threads_per_process);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_CAPACITY_SELF_TEST_PROCESSES_PREFIX,
                         runtime_statistics.capacity_self_test_process_count);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_CAPACITY_SELF_TEST_THREADS_PREFIX,
                         runtime_statistics.capacity_self_test_thread_count);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_CAPACITY_SELF_TEST_THREADS_PER_PROCESS_PREFIX,
                         runtime_statistics.capacity_self_test_threads_per_process);
    WriteRequiredMessage(vga_console,
                         OS_KERNEL_MAIN_PROCESS_THREAD_CAPACITY_SELF_TEST_PASSED_MESSAGE);
    const KernelStackManagerStatistics kernel_stack_statistics =
        GetKernelStackManager().Statistics();
    WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_KERNEL_STACK_MANAGER_READY_MESSAGE);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_KERNEL_STACK_SLOT_CAPACITY_PREFIX,
                         kernel_stack_statistics.slot_capacity);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_KERNEL_STACK_MAPPED_PAGE_COUNT_PREFIX,
                         OS_KERNEL_STACK_MAPPED_PAGE_COUNT);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_KERNEL_STACK_GUARD_PAGE_COUNT_PREFIX,
                         OS_KERNEL_STACK_GUARD_PAGE_COUNT);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_KERNEL_STACK_SIZE_PREFIX,
                         OS_KERNEL_STACK_SIZE_BYTES);
    WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_PIPE_READY_MESSAGE);

    if (selection != UserProgramSelection::Smoke &&
        selection != UserProgramSelection::OomPressure) {
        CreateRequiredProcess(vga_console, selection);
    }
}

[[nodiscard]] bool IsExpectedProcessExecutionResult(const ProcessExecutionResult &result) noexcept {
    const bool exited_successfully =
        result.termination_reason == ProcessTerminationReason::Exited &&
        result.exit_code == OS_KERNEL_MAIN_USER_EXPECTED_EXIT_CODE;
    if (result.selection == UserProgramSelection::Shell) {
        return exited_successfully &&
               result.pipe_bytes_read == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.pipe_bytes_written == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.console_bytes_read != OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.console_bytes_written != OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT;
    }
    if (result.selection == UserProgramSelection::IpcProducer) {
        return exited_successfully &&
               result.pipe_bytes_read == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.pipe_bytes_written == OS_KERNEL_MAIN_EXPECTED_PIPE_TRANSFER_SIZE_BYTES &&
               result.file_system_bytes_read == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.file_system_bytes_written == OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_SIZE_BYTES;
    }
    if (result.selection == UserProgramSelection::IpcConsumer) {
        return exited_successfully &&
               result.pipe_bytes_read == OS_KERNEL_MAIN_EXPECTED_PIPE_TRANSFER_SIZE_BYTES &&
               result.pipe_bytes_written == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.file_system_bytes_read == OS_KERNEL_MAIN_FILE_SYSTEM_PAYLOAD_SIZE_BYTES &&
               result.file_system_bytes_written == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT;
    }
    if (result.selection == UserProgramSelection::Smoke ||
        result.selection == UserProgramSelection::SchedulerWorker) {
        const bool is_file_description_proof =
            result.selection == UserProgramSelection::SchedulerWorker &&
            result.process_id == OS_KERNEL_MAIN_FILE_DESCRIPTION_PROOF_PROCESS_ID;
        const uint64_t expected_file_read_bytes =
            is_file_description_proof ? OS_KERNEL_MAIN_FILE_DESCRIPTION_PROOF_READ_BYTES
                                      : OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT;
        const uint64_t expected_file_written_bytes =
            is_file_description_proof ? OS_KERNEL_MAIN_FILE_DESCRIPTION_PROOF_WRITTEN_BYTES
                                      : OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT;
        return exited_successfully &&
               result.pipe_bytes_read == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.pipe_bytes_written == OS_KERNEL_MAIN_EXPECTED_EMPTY_PIPE_BYTE_COUNT &&
               result.file_system_bytes_read == expected_file_read_bytes &&
               result.file_system_bytes_written == expected_file_written_bytes;
    }
    if (result.selection == UserProgramSelection::InvalidOpcode) {
        return result.termination_reason == ProcessTerminationReason::Exception &&
               result.exception_vector == OS_KERNEL_MAIN_USER_INVALID_OPCODE_VECTOR;
    }
    if (result.selection == UserProgramSelection::PageFault) {
        return result.termination_reason == ProcessTerminationReason::Exception &&
               result.exception_vector == OS_KERNEL_MAIN_USER_PAGE_FAULT_VECTOR &&
               result.exception_error_code == OS_KERNEL_MAIN_USER_PAGE_FAULT_ERROR_CODE &&
               result.page_fault_address == OS_KERNEL_MAIN_USER_PAGE_FAULT_ADDRESS;
    }
    return false;
}

void WriteProcessExecutionResult(const VgaTextConsole &vga_console,
                                 const ProcessExecutionResult &result) noexcept {
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_ID_PREFIX, result.process_id);
    if (result.termination_reason == ProcessTerminationReason::Exited) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_EXIT_CODE_PREFIX,
                             static_cast<uint64_t>(result.exit_code));
    } else if (result.termination_reason == ProcessTerminationReason::Exception) {
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_EXCEPTION_VECTOR_PREFIX,
                             result.exception_vector);
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_EXCEPTION_ERROR_CODE_PREFIX,
                             result.exception_error_code);
        WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_EXCEPTION_RIP_PREFIX,
                             result.exception_instruction_pointer);
        if (result.exception_vector == OS_KERNEL_MAIN_USER_PAGE_FAULT_VECTOR) {
            WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_PAGE_FAULT_ADDRESS_PREFIX,
                                 result.page_fault_address);
        }
    }
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_USER_SYSTEM_CALL_COUNT_PREFIX,
                         result.system_call_count);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_RUN_TICKS_PREFIX,
                         result.run_tick_count);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_DISPATCH_COUNT_PREFIX,
                         result.dispatch_count);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_PIPE_READ_BYTES_PREFIX,
                         result.pipe_bytes_read);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_PIPE_WRITTEN_BYTES_PREFIX,
                         result.pipe_bytes_written);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_FILE_READ_BYTES_PREFIX,
                         result.file_system_bytes_read);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_FILE_WRITTEN_BYTES_PREFIX,
                         result.file_system_bytes_written);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_CONSOLE_READ_BYTES_PREFIX,
                         result.console_bytes_read);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_PROCESS_CONSOLE_WRITTEN_BYTES_PREFIX,
                         result.console_bytes_written);
    WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_USER_TERMINATED_MESSAGE);

    if (!IsExpectedProcessExecutionResult(result)) {
        WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_USER_RESULT_INVALID_MESSAGE);
        HaltProcessor();
    }
}

[[nodiscard]] bool
ProcessResourcesWereReclaimed(const ProcessRuntimeStatistics &statistics,
                              const uint64_t expected_process_count,
                              const uint64_t expected_virtual_address_lifecycle_count) noexcept {
    const uint64_t minimum_expected_peak_stack_count =
        expected_process_count < statistics.configured_process_capacity
            ? expected_process_count
            : statistics.configured_process_capacity;
    return ResourceSnapshotsMatch(statistics.resource_snapshot_before_processes,
                                  statistics.resource_snapshot_after_processes) &&
           statistics.resource_snapshot_difference.changed_fields_mask ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.resource_snapshot_difference.changed_field_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.frames_before_processes.managed_frame_count ==
               statistics.frames_after_processes.managed_frame_count &&
           statistics.frames_before_processes.free_frame_count ==
               statistics.frames_after_processes.free_frame_count &&
           statistics.frames_before_processes.allocated_frame_count ==
               statistics.frames_after_processes.allocated_frame_count &&
           statistics.frames_before_processes.reserved_frame_count ==
               statistics.frames_after_processes.reserved_frame_count &&
           statistics.virtual_addresses_before_processes.free_page_count ==
               statistics.virtual_addresses_after_processes.free_page_count &&
           statistics.virtual_addresses_before_processes.allocated_page_count ==
               statistics.virtual_addresses_after_processes.allocated_page_count &&
           statistics.virtual_addresses_before_processes.reserved_page_count ==
               statistics.virtual_addresses_after_processes.reserved_page_count &&
           statistics.virtual_addresses_before_processes.active_descriptor_count ==
               statistics.virtual_addresses_after_processes.active_descriptor_count &&
           statistics.virtual_addresses_after_processes.successful_allocation_count ==
               statistics.virtual_addresses_before_processes.successful_allocation_count +
                   expected_virtual_address_lifecycle_count &&
           statistics.virtual_addresses_after_processes.release_count ==
               statistics.virtual_addresses_before_processes.release_count +
                   expected_virtual_address_lifecycle_count &&
           statistics.kernel_stacks_before_processes.slot_capacity ==
               statistics.kernel_stacks_after_processes.slot_capacity &&
           statistics.kernel_stacks_before_processes.active_stack_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.kernel_stacks_after_processes.active_stack_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.kernel_stacks_after_processes.active_mapped_page_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.kernel_stacks_after_processes.active_guard_page_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.kernel_stacks_after_processes.successful_creation_count ==
               statistics.kernel_stacks_before_processes.successful_creation_count +
                   expected_virtual_address_lifecycle_count &&
           statistics.kernel_stacks_after_processes.destruction_count ==
               statistics.kernel_stacks_before_processes.destruction_count +
                   expected_virtual_address_lifecycle_count &&
           statistics.kernel_stacks_after_processes.peak_active_stack_count >=
               minimum_expected_peak_stack_count &&
           statistics.kernel_stacks_after_processes.peak_active_mapped_page_count >=
               minimum_expected_peak_stack_count * OS_KERNEL_STACK_MAPPED_PAGE_COUNT &&
           statistics.virtual_memory_areas_before_processes.capacity ==
               statistics.virtual_memory_areas_after_processes.capacity &&
           statistics.virtual_memory_areas_before_processes.active_descriptor_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.virtual_memory_areas_after_processes.active_descriptor_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.virtual_memory_areas_after_processes.free_descriptor_count ==
               statistics.virtual_memory_areas_after_processes.capacity &&
           statistics.virtual_memory_areas_after_processes.successful_acquire_count >=
               statistics.virtual_memory_areas_before_processes.successful_acquire_count &&
           statistics.virtual_memory_areas_after_processes.release_count >=
               statistics.virtual_memory_areas_before_processes.release_count &&
           statistics.virtual_memory_areas_after_processes.successful_acquire_count -
                   statistics.virtual_memory_areas_before_processes.successful_acquire_count ==
               statistics.virtual_memory_areas_after_processes.release_count -
                   statistics.virtual_memory_areas_before_processes.release_count &&
           statistics.user_page_references_before_processes.active_entry_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.user_page_references_before_processes.active_reference_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.user_page_references_after_processes.active_entry_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT &&
           statistics.user_page_references_after_processes.active_reference_count ==
               OS_KERNEL_MAIN_KERNEL_STACK_EMPTY_COUNT;
}

