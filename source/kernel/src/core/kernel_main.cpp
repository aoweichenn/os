    WriteRequiredMessage(vga_console, OS_KERNEL_MAIN_ROOTFS_V4_MOUNTED_MESSAGE);
    WriteRequiredHexLine(vga_console, OS_KERNEL_MAIN_ROOTFS_V4_REGION_SIZE_PREFIX,
                         fs::OS_KERNEL_ROOTFS_REGION_SIZE_BYTES);
